"""Generate wire types from the checked-in backend OpenAPI schema (no dependencies)."""
import json
from pathlib import Path
schemas = json.loads(Path('docs/rendering-openapi.json').read_text())['components']['schemas']
def ts(s):
    if 'const' in s: return json.dumps(s['const'])
    if 'enum' in s: return ' | '.join(json.dumps(v) for v in s['enum'])
    if 'anyOf' in s: return ' | '.join(ts(v) for v in s['anyOf'])
    t=s.get('type')
    if t=='object':
        if not s.get('properties'): return 'Record<string, '+(ts(s['additionalProperties']) if isinstance(s.get('additionalProperties'),dict) else 'never')+'>'
        return '{ '+ '; '.join(json.dumps(k)+('' if k in s.get('required',[]) else '?')+': '+ts(v) for k,v in s.get('properties',{}).items())+' }'
    if t=='array': return '('+ts(s['items'])+')[]'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(t,'unknown')
Path('app/lib/rendering-types.ts').write_text('// Generated by scripts/rendering-types.py from docs/rendering-openapi.json.\n'+ '\n'.join('export type '+k[0].upper()+k[1:]+' = '+ts(v)+';' for k,v in schemas.items())+'\n')
